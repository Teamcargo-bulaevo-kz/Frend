package com.example.assistant

/**
 * Отсев ложных срабатываний. Окно после ответа (режим диалога) слушает без слова активации, поэтому туда легко
 * попадает чужой разговор или телевизор. Реплика принимается, только если похожа на обращение к ассистенту:
 * команда, вопрос, просьба, «да/нет», «а завтра?». Шум и междометия («ага», «угу», «мм») отбрасываются.
 * Чистый Kotlin, покрыт тестами.
 */
object ListenFilter {

    private val noise = setOf(
        "ага", "угу", "мм", "ммм", "м", "э", "эм", "а", "о", "ой", "ну", "хм", "так", "вот", "да", "нет", "ок", "окей", "хорошо",
        "понятно", "ясно", "ладно", "блин", "ха", "хаха", "аха", "ах", "эх", "ух", "фу"
    )

    /** Слова, с которых начинается обращение: вопросы, просьбы, команды, продолжение разговора. */
    private val starters = setOf(
        "что", "как", "какой", "какая", "какое", "какие", "каком", "сколько", "где", "куда", "откуда", "когда", "почему", "зачем",
        "кто", "чей", "чья", "можно", "можешь", "сможешь", "расскажи", "скажи", "покажи", "найди", "включи", "выключи", "поставь",
        "открой", "закрой", "напомни", "позвони", "набери", "напиши", "отправь", "давай", "еще", "ещё", "переведи", "посчитай",
        "объясни", "продолжай", "продолжи", "дальше", "повтори", "сделай", "убери", "добавь", "запомни", "запиши", "прочитай",
        "ты", "а", "и", "а если", "сравни", "подскажи", "посоветуй", "придумай", "создай", "проверь", "узнай", "дай", "помоги",
        "разложи", "отсортируй", "сохрани", "удали", "громче", "тише", "погромче", "потише", "следующий", "следующую", "назад",
        "пауза", "стоп", "хватит", "спасибо", "привет", "мне", "у", "есть", "будет", "надо", "нужно", "хочу", "пожалуйста",
        "запусти", "сфотографируй", "сними", "разбуди", "засеки", "перемотай", "перемешай", "прибавь", "убавь", "отмени", "верни",
        "нажми", "прокрути", "листай", "вернись", "домой", "заблокируй", "покажи", "выдай", "разреши", "почисти", "освободи"
    )

    private fun words(text: String) = TextMatch.normalize(text).split(' ').filter { it.isNotEmpty() }

    /**
     * Похожа ли реплика в окне после ответа на обращение к ассистенту. [isCommand] — правила ассистента её поняли
     * (передаётся снаружи, чтобы не тянуть сюда разбор команд).
     */
    fun followUp(text: String, isCommand: Boolean = false): Boolean {
        val w = words(text)
        if (w.isEmpty()) return false
        if (isCommand) return true
        if (BargeIn.isEnd(text)) return true
        // Междометия («ага», «угу понятно») — это реакция на ответ, а не новая просьба; «да» и «нет» — ответ
        if (w.all { it in noise } && !(w.size == 1 && (w[0] == "да" || w[0] == "нет"))) return false
        if (Confirm.isYes(text) || Confirm.isNo(text)) return true
        // Слишком длинная реплика без паузы — скорее телевизор или чужой разговор
        if (w.size > 30) return false
        val first = w[0]
        val second = w.getOrNull(1)
        if (first in starters) return true
        if ((first == "ну" || first == "так" || first == "слушай" || first == "окей") && second != null && second in starters) return true
        return false
    }

    /** Слишком короткий или пустой текст после слова активации — шум распознавания, а не команда. */
    fun meaningful(text: String): Boolean {
        val w = words(text)
        return w.isNotEmpty() && !w.all { it in noise && it != "да" && it != "нет" }
    }
}

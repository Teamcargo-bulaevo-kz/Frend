package com.example.assistant

/**
 * Сбор голосовой команды из нескольких кусков. Офлайн-распознаватель закрывает фразу после ~1 с тишины,
 * поэтому «Пятница, поставь… будильник на семь» приходит двумя кусками, и раньше выполнялось одно «поставь».
 * Здесь решаем, похожа ли команда на оборванную: тогда служба ждёт продолжение несколько секунд.
 * Законченные команды выполняются сразу, без задержки. Чистый Kotlin, есть тесты.
 */
object CommandAssembler {

    /** Сколько ждать продолжения оборванной команды. */
    const val CONTINUE_MS = 3_500L

    /** Сколько кусков максимум склеиваем (дальше выполняем то, что есть). */
    const val MAX_PARTS = 3

    /** Глаголы и вопросы, после которых обязательно что-то должно идти: одни они команду не задают. */
    private val needObject = setOf(
        "поставь", "поставить", "включи", "включить", "выключи", "выключить", "отключи", "открой", "открыть",
        "запусти", "запустить", "найди", "найти", "покажи", "показать", "позвони", "позвонить", "набери",
        "напиши", "написать", "отправь", "отправить", "запиши", "записать", "запомни", "напомни", "напомнить",
        "добавь", "добавить", "удали", "удалить", "убери", "сделай", "сделать", "заведи", "разбуди", "скажи",
        "расскажи", "узнай", "переведи", "посчитай", "сколько", "какая", "какой", "какое", "какие", "где",
        "увеличь", "уменьши", "поищи", "загугли", "создай", "измени", "смени", "переключи"
    )

    /** Слова, на которых законченная фраза не обрывается: предлоги, союзы, «мне», «мой». */
    private val danglingTail = setOf(
        "на", "в", "во", "к", "ко", "до", "с", "со", "по", "про", "о", "об", "обо", "за", "от", "у", "из", "для",
        "через", "после", "перед", "под", "над", "между", "и", "или", "а", "но", "что", "чтобы", "если", "когда",
        "мой", "моя", "мою", "мое", "мои", "моему", "моей"
    )

    /** Служебные слова, которые не добавляют смысла команде. */
    private val fillers = setOf("мне", "пожалуйста", "плиз", "ка", "давай", "быстро", "срочно", "ну", "слушай", "эй")

    /** Команда похожа на оборванную паузой: одно слово-глагол (можно с «мне/пожалуйста») или конец на предлог/союз. */
    fun looksIncomplete(command: String): Boolean {
        val words = TextMatch.normalize(command).split(' ').filter { it.isNotEmpty() }
        if (words.isEmpty()) return false
        if (words.last() in danglingTail) return true
        val meaningful = words.filter { it !in fillers }
        return meaningful.size == 1 && meaningful[0] in needObject
    }

    /** Склеивает куски команды через пробел, без лишних пробелов. */
    fun join(first: String, next: String): String =
        listOf(first.trim(), next.trim()).filter { it.isNotEmpty() }.joinToString(" ")
}
